"""Generate tests/TESTS.md - the catalogue of all tests and what each one checks.

The descriptions are the test docstrings (or the test name when there is none), so the
catalogue stays in sync with the code. Run:  python tests/make_catalog.py
"""

from __future__ import annotations

import ast
from pathlib import Path

HERE = Path(__file__).parent

LAYERS = {
    "unit": ("Unit tests", "Fast, isolated checks of single building blocks: time grid and data alignment, "
                           "input validation and topology checks, and the solver adapter."),
    "validation": ("Validation tests (golden cases)",
                   "Small systems whose optimal cost or dispatch is calculated by hand (derivation in each "
                   "description). Every solved case is also checked with `assert_invariants` (see below)."),
    "integration": ("Integration tests", "Config round-trip, command line, shipped examples, UI backend (FastAPI) "
                                         "and the UI in a headless browser."),
    "performance": ("Performance tests", "Full-year runs with timing budgets (`pytest -m slow`)."),
}

HEADER = """# Test catalogue

Generated by `python tests/make_catalog.py` from the test docstrings - do not edit by hand.

Run all default tests with `pytest`, the slow performance tests with `pytest -m slow`.
Browser tests need `pip install playwright && python -m playwright install chromium` (skipped otherwise).

## Invariants checked on every validation case (`tests/helpers.py::assert_invariants`)

1. every edge flow is non-negative;
2. every bus balance closes (sum of OUT flows - sum of IN flows + slack = 0) in every step;
3. the reported flow table equals the model flow variables `m.F` exactly;
4. the cost accounting variables `m.C` add up to the solver objective;
5. storage energy stays within `[soc_min, soc_max] * e_max`;
6. the emission accounting variables `m.E` equal `sum(factor * flow * dt * weight)`.
"""


def _tests(path: Path):
    tree = ast.parse(path.read_text())
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
            doc = ast.get_docstring(node) or node.name.removeprefix("test_").replace("_", " ").capitalize() + "."
            params = ""
            for dec in node.decorator_list:
                if isinstance(dec, ast.Call) and getattr(dec.func, "attr", "") == "parametrize":
                    params = f" *(parametrized: {ast.unparse(dec.args[0])})*"
            yield node.name, " ".join(doc.split()), params


def main() -> None:
    lines = [HEADER]
    total = 0
    for layer, (title, intro) in LAYERS.items():
        files = sorted((HERE / layer).glob("test_*.py"))
        if not files:
            continue
        lines.append(f"\n## {title}\n\n{intro}\n")
        for f in files:
            mod_doc = ast.get_docstring(ast.parse(f.read_text())) or ""
            lines.append(f"\n### `{layer}/{f.name}`\n\n{mod_doc.splitlines()[0] if mod_doc else ''}\n")
            lines.append("| Test | What it checks |\n|---|---|")
            for name, doc, params in _tests(f):
                total += 1
                lines.append(f"| `{name}`{params} | {doc.replace('|', '/')} |")
    lines.insert(1, f"\n**{total} test functions.**\n")
    (HERE / "TESTS.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {HERE / 'TESTS.md'} ({total} tests)")


if __name__ == "__main__":
    main()
